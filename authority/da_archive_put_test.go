package authority

import (
	"bytes"
	"encoding/base64"
	"encoding/json"
	"os"
	"strings"
	"testing"
)

const daArchivePutVectorsPath = "testdata/da_archive_put_vectors.json"

type daArchivePutVector struct {
	Name    string             `json:"name"`
	Claims  DAArchivePutClaims `json:"claims"`
	Payload string             `json:"payload_json"`
	Token   string             `json:"token"`
}

type daArchivePutVectorFile struct {
	Source        string               `json:"source"`
	PrivateKeyHex string               `json:"private_key_hex"`
	Address       string               `json:"address"`
	Vectors       []daArchivePutVector `json:"vectors"`
}

func buildDAArchivePutVectors(t *testing.T) daArchivePutVectorFile {
	t.Helper()
	signer, err := NewSignerFromHex(payloadReleaseVectorKey)
	if err != nil {
		t.Fatal(err)
	}
	out := daArchivePutVectorFile{
		Source:        "Generated by arbiter-core authority TestDAArchivePutVectors (ARBITER_CORE_UPDATE_GOLDEN=1). The payload store copies this file to verify Arbiter archive put tokens byte for byte. Never edit by hand.",
		PrivateKeyHex: payloadReleaseVectorKey,
		Address:       signer.Address(),
	}
	for _, v := range []daArchivePutVector{
		{Name: "first_archive", Claims: DAArchivePutClaims{NetworkID: "devnet2-si-v2", ScopeKey: DAArchiveScopeKey("devnet2-si-v2", 256), PayloadHash: "0x" + strings.Repeat("ab", 32), PayloadLength: 3456789, IssuedAt: 1762840000}},
		{Name: "max_block", Claims: DAArchivePutClaims{NetworkID: "n", ScopeKey: DAArchiveScopeKey("n", 18446744073709551615), PayloadHash: "0x" + strings.Repeat("01", 32), PayloadLength: 1, IssuedAt: 1762840001}},
	} {
		token, err := signer.SignDAArchivePutAt(v.Claims)
		if err != nil {
			t.Fatalf("%s: %v", v.Name, err)
		}
		payload, err := base64.RawURLEncoding.DecodeString(strings.Split(token, ".")[1])
		if err != nil {
			t.Fatal(err)
		}
		v.Claims.Purpose, v.Claims.HolderID, v.Claims.PinPurpose = DAArchivePutPurpose, DAArchiveHolderID, DAArchivePinPurpose
		v.Payload, v.Token = string(payload), token
		out.Vectors = append(out.Vectors, v)
	}
	return out
}

// TestDAArchivePutVectors pins archive put tokens byte for byte (ES256K is
// deterministic, RFC 6979); the payload store verifies this file.
func TestDAArchivePutVectors(t *testing.T) {
	got := buildDAArchivePutVectors(t)
	encoded, err := json.MarshalIndent(got, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	encoded = append(encoded, '\n')
	if os.Getenv("ARBITER_CORE_UPDATE_GOLDEN") == "1" {
		if err := os.WriteFile(daArchivePutVectorsPath, encoded, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(daArchivePutVectorsPath)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(encoded, want) {
		t.Fatalf("%s is stale; the archive put token encoding changed:\n%s", daArchivePutVectorsPath, encoded)
	}
	for _, v := range got.Vectors {
		signer, err := recoverCompactSigner(v.Token)
		if err != nil || signer != got.Address {
			t.Fatalf("%s: recovered %q, %v; want %s", v.Name, signer, err, got.Address)
		}
	}
}

func TestSignDAArchivePutRefusesBadClaims(t *testing.T) {
	signer, err := NewSignerFromHex(payloadReleaseVectorKey)
	if err != nil {
		t.Fatal(err)
	}
	ok := DAArchivePutClaims{NetworkID: "n", ScopeKey: "history:n:5", PayloadHash: "0x01", PayloadLength: 1}
	for name, mut := range map[string]func(*DAArchivePutClaims){
		"no network":       func(c *DAArchivePutClaims) { c.NetworkID = "" },
		"other network":    func(c *DAArchivePutClaims) { c.ScopeKey = "history:m:5" },
		"not history":      func(c *DAArchivePutClaims) { c.ScopeKey = "5" },
		"zero block":       func(c *DAArchivePutClaims) { c.ScopeKey = "history:n:0" },
		"leading zero":     func(c *DAArchivePutClaims) { c.ScopeKey = "history:n:05" },
		"trailing garbage": func(c *DAArchivePutClaims) { c.ScopeKey = "history:n:5x" },
		"no hash":          func(c *DAArchivePutClaims) { c.PayloadHash = "" },
		"no length":        func(c *DAArchivePutClaims) { c.PayloadLength = 0 },
	} {
		c := ok
		mut(&c)
		if _, err := signer.SignDAArchivePutAt(c); err == nil {
			t.Errorf("%s: signed", name)
		}
	}
	token, err := signer.SignDAArchivePut("n", 5, "0x01", 1)
	if err != nil || strings.Count(token, ".") != 2 {
		t.Fatalf("SignDAArchivePut = %q, %v", token, err)
	}
}

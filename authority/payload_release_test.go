// payloadReleaseVectorsPath holds the release-token vectors the payload store
// copies into its own test data, so both sides are pinned to the same bytes.
const payloadReleaseVectorsPath = "testdata/payload_release_vectors.json"

// payloadReleaseVectorKey is a test-only authority key.
const payloadReleaseVectorKey = "4c0883a69102937d6231471b5dbb6204fe5129617082792ae468d01a3f362318"

type payloadReleaseVector struct {
	Name       string            `json:"name"`
	Key        PayloadReleaseKey `json:"key"`
	ReleaseSeq uint64            `json:"release_seq"`
	Context    ConsensusContext  `json:"context"`
	IssuedAt   int64             `json:"iat"`
	CmdHash    string            `json:"cmd_hash"`
	Payload    string            `json:"payload_json"`
	Token      string            `json:"token"`
}

type payloadReleaseVectorFile struct {
	Source        string                 `json:"source"`
	PrivateKeyHex string                 `json:"private_key_hex"`
	Address       string                 `json:"address"`
	Vectors       []payloadReleaseVector `json:"vectors"`
}

func payloadReleaseVectorInputs() []payloadReleaseVector {
	ctx := ConsensusContext{NetworkID: "devnet2-si-v2", GenesisSnapshotID: "0x" + strings.Repeat("ab", 32), AuthorityEpoch: 3}
	return []payloadReleaseVector{
		{Name: "sequenced", Key: PayloadReleaseKey{HolderID: "arbiter", Purpose: 4, ScopeKey: "1234"}, ReleaseSeq: 7<<32 | 1, Context: ctx, IssuedAt: 1762840000},
		{Name: "replay", Key: PayloadReleaseKey{HolderID: "arbiter", Purpose: 1, ScopeKey: "42"}, ReleaseSeq: 7<<32 | 2, Context: ctx, IssuedAt: 1762840001},
		{Name: "audit_max_scope", Key: PayloadReleaseKey{HolderID: "arbiter", Purpose: 2, ScopeKey: "18446744073709551615"}, ReleaseSeq: 1<<63 | 1<<32 | 4294967295, Context: ctx, IssuedAt: 1762840002},
		{Name: "epoch_zero", Key: PayloadReleaseKey{HolderID: "arbiter", Purpose: 1, ScopeKey: "1"}, ReleaseSeq: 1<<32 | 1, Context: ConsensusContext{NetworkID: "n", GenesisSnapshotID: "g", AuthorityEpoch: 0}, IssuedAt: 1762840003},
	}
}

func buildPayloadReleaseVectors(t *testing.T) payloadReleaseVectorFile {
	t.Helper()
	signer, err := NewSignerFromHex(payloadReleaseVectorKey)
	if err != nil {
		t.Fatal(err)
	}
	out := payloadReleaseVectorFile{
		Source:        "Generated by arbiter-core authority TestPayloadReleaseVectors (ARBITER_CORE_UPDATE_GOLDEN=1). The payload store copies this file to verify Arbiter release tokens byte for byte. Never edit by hand.",
		PrivateKeyHex: payloadReleaseVectorKey,
		Address:       signer.Address(),
	}
	for _, v := range payloadReleaseVectorInputs() {
		hash, err := PayloadReleaseKeyHash(v.Key)
		if err != nil {
			t.Fatal(err)
		}
		token, err := signer.SignPayloadReleaseAt(v.Key, v.ReleaseSeq, v.Context, v.IssuedAt)
		if err != nil {
			t.Fatalf("%s: %v", v.Name, err)
		}
		payload, err := base64.RawURLEncoding.DecodeString(strings.Split(token, ".")[1])
		if err != nil {
			t.Fatal(err)
		}
		v.CmdHash, v.Payload, v.Token = hash, string(payload), token
		out.Vectors = append(out.Vectors, v)
	}
	return out
}

// TestPayloadReleaseVectors pins release tokens byte for byte. ES256K
// signing is deterministic (RFC 6979), so the tokens are reproducible.
func TestPayloadReleaseVectors(t *testing.T) {
	got := buildPayloadReleaseVectors(t)
	encoded, err := json.MarshalIndent(got, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	encoded = append(encoded, '\n')
	if os.Getenv("ARBITER_CORE_UPDATE_GOLDEN") == "1" {
		if err := os.MkdirAll(filepath.Dir(payloadReleaseVectorsPath), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(payloadReleaseVectorsPath, encoded, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(payloadReleaseVectorsPath)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(encoded, want) {
		t.Fatalf("%s is stale; the release token encoding changed:\n%s", payloadReleaseVectorsPath, encoded)
	}
	for _, v := range got.Vectors {
		signer, err := recoverCompactSigner(v.Token)
		if err != nil || signer != got.Address {
			t.Fatalf("%s: recovered %q, %v; want %s", v.Name, signer, err, got.Address)
		}
	}
}

// TestPayloadReleaseKeyHashMatchesStoreVectors checks the key hash against
// digests the payload store pins from housegate pkg/replay.CanonicalDigest
// (its canonical_digest_vectors.json, generated independently of this code).
func TestPayloadReleaseKeyHashMatchesStoreVectors(t *testing.T) {
	cases := []struct {
		key  PayloadReleaseKey
		want string
	}{
		{PayloadReleaseKey{HolderID: "arbiter", Purpose: 1, ScopeKey: "42"}, "0x9274612a7b7274cc6652955ef9d40a5672ff5aebf64e5f3dbc929360f88eeb6a"},
		{PayloadReleaseKey{HolderID: "arbiter", Purpose: 2, ScopeKey: "18446744073709551615"}, "0x802f98b02a1b43de9062c053f7a1ded845485822290c7f19ad72d9402b3a0a03"},
		{PayloadReleaseKey{HolderID: "operator", Purpose: 3, ScopeKey: "legal-hold/2026-11"}, "0x83c7ae317c900f653c24158601e5c68f4b0fee733f0ea26fd1ba0463b0236e6d"},
	}
	for _, c := range cases {
		got, err := PayloadReleaseKeyHash(c.key)
		if err != nil || got != c.want {
			t.Fatalf("PayloadReleaseKeyHash(%+v) = %s, %v; want %s", c.key, got, err, c.want)
		}
	}
}

func TestSignPayloadReleaseRefusesIncompleteInput(t *testing.T) {
	signer, err := NewSignerFromHex(payloadReleaseVectorKey)
	if err != nil {
		t.Fatal(err)
	}
	key := PayloadReleaseKey{HolderID: "arbiter", Purpose: 1, ScopeKey: "1"}
	ctx := ConsensusContext{NetworkID: "n", GenesisSnapshotID: "g"}
	for name, call := range map[string]func() error{
		"zero seq": func() error { _, err := signer.SignPayloadRelease(key, 0, ctx); return err },
		"no holder": func() error {
			_, err := signer.SignPayloadRelease(PayloadReleaseKey{Purpose: 1, ScopeKey: "1"}, 1, ctx)
			return err
		},
		"no purpose": func() error {
			_, err := signer.SignPayloadRelease(PayloadReleaseKey{HolderID: "a", ScopeKey: "1"}, 1, ctx)
			return err
		},
		"no scope": func() error {
			_, err := signer.SignPayloadRelease(PayloadReleaseKey{HolderID: "a", Purpose: 1}, 1, ctx)
			return err
		},
		"no network": func() error {
			_, err := signer.SignPayloadRelease(key, 1, ConsensusContext{GenesisSnapshotID: "g"})
			return err
		},
		"no genesis id": func() error {
			_, err := signer.SignPayloadRelease(key, 1, ConsensusContext{NetworkID: "n"})
			return err
		},
	} {
		if call() == nil {
			t.Fatalf("%s: want refusal", name)
		}
	}
}

func TestPackReleaseSeq(t *testing.T) {
	got, err := PackReleaseSeq(7, 2)
	if err != nil || got != 7<<32|2 {
		t.Fatalf("PackReleaseSeq(7, 2) = %d, %v", got, err)
	}
	a, _ := PackReleaseSeq(7, 1<<32-1)
	b, _ := PackReleaseSeq(8, 1)
	if a >= b {
		t.Fatalf("a later term must sign above every earlier seq: %d >= %d", a, b)
	}
	for _, c := range [][2]uint64{{0, 1}, {1 << 32, 1}, {1, 0}, {1, 1 << 32}} {
		if _, err := PackReleaseSeq(c[0], c[1]); err == nil {
			t.Fatalf("PackReleaseSeq(%d, %d): want error", c[0], c[1])
		}
	}
}
